#!/usr/bin/env node
/**
 * Runs Halaqati on your own computer (Docker), with its data saved locally.
 *
 *   npm run local:setup -- you@example.com   first time: secrets + owner email
 *   npm run local:up                          start (http://localhost:3000)
 *   npm run local:down                        stop (data is kept)
 *   npm run local:backup                      save a copy to ./backups
 *   npm run local:restore -- <file> --yes     replace the data with a backup
 *   npm run local:logs                        follow the logs
 */
import { spawn, spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const envFile = path.join(here, ".env");
const compose = ["compose", "--env-file", envFile, "-f", path.join(here, "docker-compose.yml")];
const [cmd = "help", ...args] = process.argv.slice(2);

const die = (msg) => { console.error(`✗ ${msg}`); process.exit(1); };
const ok = (msg) => console.log(`✓ ${msg}`);

function docker(argv, opts = {}) {
  const r = spawnSync("docker", argv, { stdio: "inherit", ...opts });
  if (r.error) die("Docker غير مثبت أو لا يعمل. ثبّت Docker Desktop وشغّله ثم أعد المحاولة.");
  return r.status ?? 1;
}

function requireEnv() {
  if (!fs.existsSync(envFile)) die('شغّل أولًا: npm run local:setup -- بريدك@example.com');
}

/** HS256 JWT with the local secret (anon / service_role keys). */
function sign(payload, secret) {
  const b64 = (o) => Buffer.from(JSON.stringify(o)).toString("base64url");
  const data = `${b64({ alg: "HS256", typ: "JWT" })}.${b64(payload)}`;
  return `${data}.${crypto.createHmac("sha256", secret).update(data).digest("base64url")}`;
}

function setup() {
  const email = (args.find((a) => a.includes("@")) ?? "").trim().toLowerCase();
  if (fs.existsSync(envFile)) {
    if (email) {
      const text = fs.readFileSync(envFile, "utf8").replace(/^ADMIN_EMAIL=.*$/m, `ADMIN_EMAIL=${email}`);
      fs.writeFileSync(envFile, text, { mode: 0o600 });
      ok(`حُدّث بريد المالك: ${email}`);
    } else ok("الإعداد موجود مسبقًا (local/.env). لن تُغيَّر الأسرار حتى لا تضيع البيانات.");
    return;
  }
  const rand = () => crypto.randomBytes(24).toString("hex");
  const jwt = crypto.randomBytes(48).toString("hex");
  const exp = Math.floor(Date.now() / 1000) + 20 * 365 * 24 * 3600;
  const port = args.find((a) => /^--port=\d+$/.test(a))?.split("=")[1] ?? "3000";
  const site = args.find((a) => a.startsWith("--site="))?.slice(7) ?? `http://localhost:${port}`;
  const lines = [
    "# Halaqati local secrets — keep private, never commit. Generated by local/halaqati.mjs",
    `POSTGRES_PASSWORD=${rand()}`,
    `AUTHENTICATOR_PASSWORD=${rand()}`,
    `JWT_SECRET=${jwt}`,
    `ANON_KEY=${sign({ role: "anon", iss: "halaqati-local", exp }, jwt)}`,
    `SERVICE_KEY=${sign({ role: "service_role", iss: "halaqati-local", exp }, jwt)}`,
    `SITE_URL=${site}`,
    `APP_PORT=${port}`,
    `ADMIN_EMAIL=${email}`,
  ];
  fs.writeFileSync(envFile, lines.join("\n") + "\n", { mode: 0o600 });
  ok("أُنشئت الأسرار في local/.env");
  if (email) ok(`سيحصل ${email} على كل الأدوار عند إنشاء حسابه.`);
  else console.log("نصيحة: أعد التشغيل مع بريدك لتحصل على كل الأدوار: npm run local:setup -- you@example.com");
}

function backup() {
  requireEnv();
  const dir = path.join(root, "backups");
  fs.mkdirSync(dir, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:T]/g, "-").slice(0, 19);
  const file = path.join(dir, `halaqati-${stamp}.dump`);
  const out = fs.openSync(file, "w", 0o600);
  const status = docker([...compose, "exec", "-T", "db", "pg_dump", "-U", "postgres", "-d", "halaqati", "-Fc"], { stdio: ["ignore", out, "inherit"] });
  fs.closeSync(out);
  if (status !== 0 || fs.statSync(file).size === 0) { fs.rmSync(file, { force: true }); die("فشل النسخ. هل المنصة تعمل؟ (npm run local:up)"); }
  ok(`حُفظت نسخة: ${path.relative(root, file)} (${Math.round(fs.statSync(file).size / 1024)} ك.ب)`);
}

function restore() {
  requireEnv();
  const file = args.find((a) => !a.startsWith("--"));
  if (!file || !fs.existsSync(file)) die("حدّد ملف النسخة: npm run local:restore -- backups/halaqati-....dump --yes");
  if (!args.includes("--yes")) die("الاستعادة تستبدل البيانات الحالية بالكامل. أضف --yes للتأكيد (يُنصح بأخذ نسخة أولًا).");
  docker([...compose, "stop", "app", "gateway", "rest", "auth"]);
  const input = fs.openSync(file, "r");
  const status = docker([...compose, "exec", "-T", "db", "pg_restore", "-U", "postgres", "-d", "halaqati", "--clean", "--if-exists", "--no-owner", "--single-transaction"], { stdio: [input, "inherit", "inherit"] });
  fs.closeSync(input);
  docker([...compose, "up", "-d"]);
  if (status !== 0) die("فشلت الاستعادة؛ لم تتغير البيانات.");
  ok("استُعيدت البيانات.");
}

switch (cmd) {
  case "setup":
    setup();
    break;
  case "up": {
    requireEnv();
    if (docker([...compose, "up", "-d", "--build"]) !== 0) die("تعذّر التشغيل. راجع: npm run local:logs");
    const port = (fs.readFileSync(envFile, "utf8").match(/^APP_PORT=(\d+)/m) ?? [])[1] ?? "3000";
    ok(`حلقتي تعمل على جهازك: http://localhost:${port}`);
    break;
  }
  case "down":
    requireEnv();
    docker([...compose, "down"]);
    ok("توقفت المنصة. البيانات محفوظة وستعود عند التشغيل.");
    break;
  case "logs":
    requireEnv();
    spawn("docker", [...compose, "logs", "-f", "--tail", "100"], { stdio: "inherit" });
    break;
  case "backup":
    backup();
    break;
  case "restore":
    restore();
    break;
  default:
    console.log(fs.readFileSync(fileURLToPath(import.meta.url), "utf8").split("*/")[0].replace(/^#!.*\n\/\*\*/, "").replace(/^ \* ?/gm, ""));
}
